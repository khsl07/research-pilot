import datetime
from typing import Optional
from src.schemas.verification import FinalResearchReport, CitationAuditReport
from src.schemas.conflict import ConflictReport

def generate_markdown_bundle(
    report: FinalResearchReport,
    conflict_report: Optional[ConflictReport] = None,
    audit_report: Optional[CitationAuditReport] = None,
) -> str:
    """Generate a clean, standalone Markdown document with verification metadata."""
    approval_badge = "✅ Approved by Human Lead" if report.approved_by_user else "⚠️ Draft - Pending Human Approval"
    approval_time = report.approval_timestamp or "Not approved"

    header = f"""# {report.title}

> **Document Status**: {approval_badge}  
> **Topic**: {report.topic}  
> **Generated by**: ResearchPilot Agentic System  
> **Approval Timestamp**: {approval_time}  

---

"""
    content = report.full_markdown

    # Append Audit Appendix if available
    appendix = ""
    if audit_report:
        appendix += f"\n\n---\n\n## Appendix: Citation Verification Audit Report\n\n"
        appendix += f"- **Overall Fidelity Score**: {audit_report.fidelity_score}%\n"
        appendix += f"- **Credibility Verdict**: {audit_report.verdict}\n"
        appendix += f"- **Claims Audited**: {audit_report.total_claims_checked} ({audit_report.verified_count} verified, {audit_report.flagged_count} flagged)\n\n"
        appendix += "| Claim Excerpt | Citation | Status | Confidence | Audit Warning |\n"
        appendix += "| :--- | :---: | :---: | :---: | :--- |\n"
        for item in audit_report.items:
            warn = item.flag_warning or "None (Supported)"
            excerpt = item.claim_text.replace("\n", " ").strip()[:65] + "..."
            appendix += f"| {excerpt} | [{item.citation_index}] | **{item.status}** | {int(item.confidence_score*100)}% | {warn} |\n"

    return header + content + appendix

def generate_html_report(markdown_content: str, title: str) -> str:
    """Wrap content in a standalone, printable HTML template."""
    import html
    # Simple markdown-to-html converter
    lines = markdown_content.split("\n")
    html_lines = []
    in_table = False

    for line in lines:
        if line.startswith("# "):
            html_lines.append(f"<h1 style='color: #1e293b; border-bottom: 2px solid #3b82f6; padding-bottom: 8px;'>{line[2:]}</h1>")
        elif line.startswith("## "):
            html_lines.append(f"<h2 style='color: #1e3a8a; margin-top: 24px;'>{line[3:]}</h2>")
        elif line.startswith("### "):
            html_lines.append(f"<h3 style='color: #2563eb;'>{line[4:]}</h3>")
        elif line.startswith("> "):
            html_lines.append(f"<blockquote style='border-left: 4px solid #3b82f6; background: #f8fafc; padding: 10px 16px; margin: 12px 0;'>{line[2:]}</blockquote>")
        elif line.startswith("- "):
            html_lines.append(f"<li style='margin-bottom: 6px;'>{line[2:]}</li>")
        elif line.startswith("|") and "---" in line:
            continue
        elif line.startswith("|"):
            cells = [c.strip() for c in line.split("|")[1:-1]]
            tag = "th style='background:#f1f5f9; padding:8px; border:1px solid #cbd5e1;'" if not in_table else "td style='padding:8px; border:1px solid #cbd5e1;'"
            row = "".join([f"<{tag}>{c}</{tag.split()[0]}>" for c in cells])
            if not in_table:
                html_lines.append("<table style='width:100%; border-collapse:collapse; margin:16px 0;'>")
                in_table = True
            html_lines.append(f"<tr>{row}</tr>")
        elif in_table and not line.startswith("|"):
            html_lines.append("</table>")
            in_table = False
            html_lines.append(f"<p>{line}</p>")
        elif line.strip():
            html_lines.append(f"<p style='line-height: 1.6; color: #334155;'>{line}</p>")

    if in_table:
        html_lines.append("</table>")

    body_html = "\n".join(html_lines)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>{title}</title>
    <style>
        body {{
            font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
            max-width: 900px;
            margin: 40px auto;
            padding: 0 20px;
            color: #1e293b;
            background: #ffffff;
        }}
        @media print {{
            body {{ max-width: 100%; margin: 0; padding: 15mm; }}
            a {{ text-decoration: none; color: #000; }}
        }}
    </style>
</head>
<body>
    {body_html}
</body>
</html>"""
